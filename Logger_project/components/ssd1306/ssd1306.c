static void send_command(uint8_t cmd) {
	uint8_t data[2] = {0x00, cmd};
	i2c_master_write_to_device(_i2c_num, SSD1306_I2C_ADDR, data, 2,
							   pdMS_TO_TICKS(100));
}

void ssd1306_init(i2c_port_t i2c_num) {
	_i2c_num = i2c_num;
	vTaskDelay(pdMS_TO_TICKS(100));

	send_command(0xAE); // Display OFF
	send_command(0xD5);
	send_command(0x80); // Set display clock divide ratio
	send_command(0xA8);
	send_command(0x3F); // Multiplex ratio
	send_command(0xD3);
	send_command(0x00); // Display offset
	send_command(0x40); // Start line
	send_command(0x8D);
	send_command(0x14); // Charge pump
	send_command(0x20);
	send_command(0x00); // Memory mode (horizontal)
	send_command(0xA1); // Segment remap
	send_command(0xC8); // Com output scan direction
	send_command(0xDA);
	send_command(0x12); // COM pins hardware config
	send_command(0x81);
	send_command(0xCF); // Contrast
	send_command(0xD9);
	send_command(0xF1); // Pre-charge period
	send_command(0xDB);
	send_command(0x40); // VCOMh deselect level
	send_command(0xA4); // Entire display on
	send_command(0xA6); // Normal display
	send_command(0xAF); // Display ON
	ssd1306_clear();
}

void ssd1306_clear(void) { memset(GRAM, 0, sizeof(GRAM)); }

void ssd1306_draw_string(uint8_t x, uint8_t line, const char *str) {
	uint8_t idx = x;
	while (*str && idx < 21) {
		char c = *str++;
		const uint8_t *glyph = font5x7[(int)c];
		if (!glyph)
			glyph = font5x7[' '];

		for (uint8_t i = 0; i < 5; i++) {
			GRAM[line * 128 + idx * 6 + i] = glyph[i];
		}
		GRAM[line * 128 + idx * 6 + 5] = 0x00; // Інтервал між символами
		idx++;
	}
}

void ssd1306_refresh(void) {
	send_command(0x21);
	send_command(0);
	send_command(127);
	send_command(0x22);
	send_command(0);
	send_command(7);

	uint8_t tx_buf[129];
	tx_buf[0] = 0x40; // Data stream command
	for (int page = 0; page < 8; page++) {
		memcpy(&tx_buf[1], &GRAM[page * 128], 128);
		i2c_master_write_to_device(_i2c_num, SSD1306_I2C_ADDR, tx_buf, 129,
								   pdMS_TO_TICKS(100));
	}
}